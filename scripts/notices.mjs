// Generates THIRD_PARTY_NOTICES.md from the Go modules linked into the
// binary and the production npm packages bundled into the frontend.
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const licenseNames = /^(LICEN[CS]E|COPYING|NOTICE)(\.(md|txt))?$/i

function licenseTexts(directory) {
  if (!existsSync(directory)) return []
  return readdirSync(directory)
    .filter((name) => licenseNames.test(name))
    .sort()
    .map((name) => ({ name, text: readFileSync(join(directory, name), 'utf8').trim() }))
}

function goModules() {
  const output = execFileSync(
    'go',
    ['list', '-deps', '-f', '{{with .Module}}{{.Path}} {{.Version}} {{.Dir}}{{end}}', './cmd/sshworkbench'],
    { cwd: root, encoding: 'utf8', env: { ...process.env, GOFLAGS: '-mod=mod' } },
  )
  const modules = new Map()
  for (const line of output.split('\n')) {
    const [path, version, directory] = line.split(' ')
    if (!path || path === 'sshworkbench' || !version) continue
    modules.set(path, { name: path, version, licenses: licenseTexts(directory) })
  }
  return [...modules.values()].sort((first, second) => first.name.localeCompare(second.name))
}

function npmPackages() {
  const lock = JSON.parse(readFileSync(join(root, 'web/package-lock.json'), 'utf8'))
  const packages = []
  for (const [location, metadata] of Object.entries(lock.packages ?? {})) {
    if (!location.startsWith('node_modules/') || metadata.dev || metadata.devOptional) continue
    const name = location.slice(location.lastIndexOf('node_modules/') + 'node_modules/'.length)
    packages.push({
      name,
      version: metadata.version,
      declared: metadata.license,
      licenses: licenseTexts(join(root, 'web', location)),
    })
  }
  return packages.sort((first, second) => first.name.localeCompare(second.name))
}

const sections = [
  '# Third-party notices',
  '',
  'SSH Workbench links or bundles the following open-source components. This file is generated by `make notices`; do not edit it by hand.',
  '',
]
for (const [title, items] of [
  ['Go modules', goModules()],
  ['Frontend packages', npmPackages()],
]) {
  sections.push(`## ${title}`, '')
  for (const item of items) {
    sections.push(`### ${item.name} ${item.version}`, '')
    if (item.declared) sections.push(`Declared license: ${item.declared}`, '')
    if (item.licenses.length === 0) sections.push('_No license file found in the distributed package; see the upstream project._', '')
    for (const license of item.licenses) sections.push('```text', license.text, '```', '')
  }
}
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), sections.join('\n'))
console.log('Wrote THIRD_PARTY_NOTICES.md')
